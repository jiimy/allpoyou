-- access_logs: 접속 IP / 유저 기록
-- 비로그인 시 user_id 는 NULL 이어야 합니다.

create table if not exists public.access_logs (
  id bigint generated by default as identity primary key,
  user_id bigint null references public.users (id) on delete set null,
  ip_address text not null,
  created_at timestamptz not null default now()
);

create index if not exists access_logs_user_id_created_at_idx
  on public.access_logs (user_id, created_at desc);

create index if not exists access_logs_ip_created_at_idx
  on public.access_logs (ip_address, created_at desc);

-- 이미 NOT NULL 로 만들어진 경우 실행:
alter table public.access_logs
  alter column user_id drop not null;
